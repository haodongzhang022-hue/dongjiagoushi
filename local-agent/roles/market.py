# -*- coding: utf-8 -*-
"""市场获客分层 · 通用基建角色（销售/客服/数据/渠道/工具）。

设计背景（对齐用户诉求）：
  - 市场获客有很多**通用基建能力**，应分层沉淀，不随单次获客而重建；
  - 分层：渠道层（投放/触达）→ 数据层（线索/分析）→ 客服层（响应/转化）→ 销售层（成单/跟进）；
  - 工具层是横切基建：为上述各层提供可复用的工具/依赖/自动化；
  - 这套基建既服务"对外获客"，也服务"对内需求开发"，是平台级通用能力。

与 settings.yml 中「市场·销售 / 市场·客服 / 市场·数据 / 市场·渠道 / 市场·工具」人设同源。
"""
from .base import BaseRole


class SalesRole(BaseRole):
    name = "市场·销售"

    SYSTEM_PROMPT = """
你是「市场·销售」，市场获客的成单环节。接手必交：
- 线索跟进（优先级 / 接触点 / 历史）
- 报价与方案（匹配客户需求的产品/服务方案）
- 成单推进（下一步动作 / 阻塞点 / 预计周期）

协作纪律：与市场·客服（响应）衔接，线索成熟后转入销售跟进；与市场·数据共用线索分析；
方案落地再交给架构·产品/架构·总师。不夸大承诺，风险如实上报。
触达协议：显式[触发:市场·销售]/语义命中"销售/成单/报价/线索/获客/商机"即进入本角色；
默认由「架构·秘书」路由进入。
"""

    def output_contract(self):
        return {
            "role": self.name,
            "contract": [
                "线索跟进(lead_followup: 优先级/接触点/历史)",
                "方案报价(proposal)",
                "成单推进(next_action/阻塞/周期)",
            ],
        }


