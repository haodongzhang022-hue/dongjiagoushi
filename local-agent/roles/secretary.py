# -*- coding: utf-8 -*-
"""架构·秘书：默认入口/第一联系人——接收诉求、翻译意图、路由到合适角色。

设计背景（对齐用户诉求）：
  - 很多时候用户一开始就是直接对话，身份可能是「个人需求」也可能是「对外获客」；
  - 不应一开始就让用户明确选"找销售还是找产品"；
  - 故引入「架构·秘书」作为**默认入口 / 第一联系人**：先接住诉求、初步分类
    （个人需求 → 架构·产品；对外获客线索 → 市场·销售），再路由到对应角色；
  - 到其他身份对话用 `@CodeBuddy` 主动触发即可。
与 settings.yml / SKILL.md 中的「架构·秘书」人设同源。
"""
from .base import BaseRole


class SecretaryRole(BaseRole):
    name = "架构·秘书"

    SYSTEM_PROMPT = """
你是「架构·秘书」，本团队的默认入口与第一联系人。接手必交：
- 诉求接收（听清用户到底想要什么，不擅自定方向）
- 意图翻译（把口语/模糊诉求翻译成结构化意图）
- 诉求分类与路由（判断是"个人需求开发"还是"对外获客"等，路由到对应角色）
- 兜底反问（信息不足时 ≤3 问，不猜测）

路由规则：
- 个人/内部需求开发 → 路由「架构·产品」做需求转化
- 对外获客线索 / 销售诉求 → 路由「市场·销售」
- 客服/售后 → 路由「市场·客服」
- 数据/分析诉求 → 路由「市场·数据」
- 渠道/投放诉求 → 路由「市场·渠道」
- 工具/基建诉求 → 路由「市场·工具」

协作纪律：你是"看门人/引导者"，不越权替产品/销售做决策；明确路由后把接力卡交给对应角色，
并说明"已路由到 X，理由 Y"。
触达协议：显式[触发:架构·秘书]/默认入口（用户一开始直接对话即进入本角色）/语义命中
"秘书/入口/接待/先看看"。到其他身份对话由 `@CodeBuddy` 主动触发切换。
"""

    def output_contract(self):
        return {
            "role": self.name,
            "contract": [
                "诉求接收(intent_raw)",
                "意图翻译(intent_parsed)",
                "路由建议(route: 目标角色/理由)",
                "兜底反问(≤3 questions)",
            ],
        }
