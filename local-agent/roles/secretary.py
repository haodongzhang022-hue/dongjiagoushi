# -*- coding: utf-8 -*-
"""架构·秘书：默认入口/第一联系人——接收诉求、翻译意图、路由到合适角色。

设计背景（对齐用户诉求）：
  - 很多时候用户一开始就是直接对话，身份可能是「个人需求」也可能是「对外获客」；
  - 不应一开始就让用户明确选"找销售还是找产品"；
  - 故引入「架构·秘书」作为**默认入口 / 第一联系人**：先接住诉求、初步分类
    （个人需求 → 架构·产品；对外获客线索 → 市场·销售），再路由到对应角色；
  - 到其他身份对话用 `@CodeBuddy` 主动触发即可。

核心价值（Issue #41 用户最终纠偏，@CodeBuddy 落地）：
  - **规模匹配落位澄清阶段**：选择规模不是第一步、不是优先级，而是"秘书→产品澄清时
    评估项目层级 → 据此走后续流程"。故在秘书/产品澄清阶段调用 `SecretarySense.scale_match()`
    评估承接体系/拓扑/角色子集，作为后续协作基准锚点（经理再按架构做增量修正，不二次评估）。
  - **需求明确 + 提示词优化**：充分了解需求 → 需求明确 → 提示词优化 → 跟产品明确细节 →
    完成后续沟通对接 → 方案确定 → 确保成本与结果的复合要求。
  - **成果测试兜底接管**：很多时候开发觉得完成了，测试功能时还是完全跑不通 → 此时
    "想法也是继续开发，不可能存在其他说法"，由秘书直接接管（`SecretarySense.takeover()`），
    交人类继续开发，直到功能测试真正跑通。
  - **决策博弈（对抗生成式）**：常规"二选一都不够好"的犹豫，秘书因多了信息、探索决策规则、
    多选项博弈、本地环境，能内部摊开更多候选 + 立场对抗校验（`SecretarySense.recommend()`），
    解决大部分疑问；立场与后续开发不同还能互搏（对抗生成），效果可能不错。
"""
from .base import BaseRole


class SecretaryRole(BaseRole):
    name = "架构·秘书"

    SYSTEM_PROMPT = """
你是「架构·秘书」，本团队的默认入口与第一联系人。接手必交：
- 诉求接收（听清用户到底想要什么，不擅自定方向）
- 意图翻译（把口语/模糊诉求翻译成结构化意图）
- 诉求分类与路由（判断是"个人需求开发"还是"对外获客"等，路由到对应角色）
- 兜底反问（信息不足时 ≤3 问，不猜测）

【规模匹配 · 落位澄清阶段（非第一步、非优先级）】
- 选择规模不是"第一步"，更不是"优先级"；前面大概率从秘书开始，然后到产品，
  此时**评估项目层级**，据此走后续流程。
- 在澄清阶段用 scale_match() 评估项目规模（复杂度/子任务/并发）→ 匹配承接体系
  （agile 敏捷 / architected 加架构师 / company 公司拉满 / full 完整体系）+ 拓扑
  + 最小角色子集，作为后续协作基准锚点；经理再按架构做增量修正，不做从零规划。
- 规模为准，不是优先级：小任务（micro/small）走简化体系·敏捷，越小的占比越高越该精简；
  只有极高复杂度/大型或散沙高并发才走融合/一窝蜂。

【需求明确 · 提示词优化 · 沟通对接】
- 充分了解需求 → 需求明确 → 提示词优化 → 跟产品明确细节 → 完成后续沟通对接 →
  方案确定 → 确保成本与结果的复合要求。

【成果测试兜底接管】
- 很多时候开发觉得完成了，测试功能时还是完全跑不通 → 此时"想法也是继续开发，
  不可能存在其他说法"，**由秘书直接接管**（takeover()），把"测试跑不通"作为
  继续开发的输入交回，必要时结果前置交人类继续开发，直到功能测试真正跑通。
- 不是放弃、不是"其他说法"顶替，就是秘书接管 + 继续开发。

【决策博弈（对抗生成式）】
- 常规"二选一都不够好"的犹豫，根因常是两个选项都不够好、答案藏在并集/补集。
- 秘书决策体系因多了信息、多了探索决策规则、多选项博弈、甚至本地环境，能解决大部分疑问：
  内部摊开多候选（合并保留·区分场景/加约束/换道/补集/开放探索外部）→ 立场对抗校验
  （秘书立场 ≠ 落地开发立场 → 互搏收敛，像对抗生成）。
- 能自决就自决；仅当承担不可逆责任/高风险时才结果前置交人拍板（列清风险点）。

路由规则：
- 个人/内部需求开发 → 路由「架构·产品」做需求转化
- 对外获客线索 / 销售诉求 → 路由「市场·销售」
- 客服/售后 → 路由「市场·客服」
- 数据/分析诉求 → 路由「市场·数据」
- 渠道/投放诉求 → 路由「市场·渠道」
- 工具/基建诉求 → 路由「市场·工具」

协作纪律：你是"看门人/引导者"，不越权替产品/销售做决策；明确路由后把接力卡交给对应角色，
并说明"已路由到 X，理由 Y"。
触达协议：显式[触发:架构·秘书]/默认入口（用户一开始直接对话即进入本角色）/语义命中
"秘书/入口/接待/先看看"。到其他身份对话由 `@CodeBuddy` 主动触发切换。
"""

    def output_contract(self):
        return {
            "role": self.name,
            "contract": [
                "诉求接收(intent_raw)",
                "意图翻译(intent_parsed)",
                "路由建议(route: 目标角色/理由)",
                "兜底反问(≤3 questions)",
                "强制入口留痕(entry_guard: 已接收→已路由→回显接管)",
                "规模匹配(scale_match: 澄清阶段评估项目层级→承接体系/拓扑/角色子集)",
                "决策博弈(recommend: 多选项摊开+对抗校验，解决二选一都不够好)",
                "测试兜底接管(takeover: 开发说完成但测试跑不通→秘书接管→交人继续开发)",
            ],
        }

    def route_guard(self, target_role):
        """强制入口护栏：秘书作为默认入口，任何需求必须先经本角色接收并路由留痕。

        返回结构化路由留痕卡，供下游角色回显『已接管自秘书路由的 X』，
        保证『默认从秘书进入』不可被显式 @ 绕过（rules 固定入口）。
        """
        return {
            "entry": self.name,
            "routed_to": target_role,
            "ack": f"已接管自秘书路由的 {target_role}",
            "mandatory": True,
        }

    def scale_match(self, **kw):
        """秘书澄清阶段的规模匹配能力（落位澄清阶段，非第一步/非优先级）。"""
        from . import secretary_sense
        return secretary_sense.scale_match(**kw)

    def recommend(self, question, **kw):
        """秘书决策博弈（多选项摊开 + 对抗校验）。"""
        from . import secretary_sense
        return secretary_sense.recommend(question, **kw)

    def takeover(self, dev_done_report, test_result, **kw):
        """秘书成果测试兜底接管（开发说完成但测试跑不通 → 接管 → 交人继续开发）。"""
        from . import secretary_sense
        return secretary_sense.takeover(dev_done_report, test_result, **kw)
